import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import fs from 'node:fs';
const doc = await PDFDocument.create();
const font = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const p1 = doc.addPage([595, 842]);
p1.drawText('Invoice #1042', { x: 60, y: 760, size: 28, font: bold, color: rgb(0.1, 0.1, 0.4) });
p1.drawText('Billed to: Roosevelt Ase', { x: 60, y: 720, size: 14, font });
p1.drawText('Total due: $250.00', { x: 60, y: 696, size: 14, font });
p1.drawText('Please pay within 14 days of receipt.', { x: 60, y: 660, size: 12, font });
p1.drawRectangle({ x: 60, y: 560, width: 475, height: 60, borderColor: rgb(0.7, 0.7, 0.7), borderWidth: 1 });
p1.drawText('Signature:', { x: 70, y: 500, size: 12, font });
const form = doc.getForm();
const name = form.createTextField('fullName'); name.addToPage(p1, { x: 60, y: 440, width: 220, height: 22 });
const agree = form.createCheckBox('agree'); agree.addToPage(p1, { x: 60, y: 400, width: 16, height: 16 });
p1.drawText('I agree to the terms', { x: 84, y: 404, size: 12, font });
const dd = form.createDropdown('plan'); dd.addOptions(['Basic', 'Pro', 'Enterprise']); dd.addToPage(p1, { x: 60, y: 350, width: 160, height: 22 });
const p2 = doc.addPage([595, 842]);
p2.drawText('Page two: terms and conditions', { x: 60, y: 760, size: 20, font: bold });
p2.drawText('Late payments incur a 5% fee.', { x: 60, y: 730, size: 12, font });
fs.writeFileSync('test/sample.pdf', await doc.save());
console.log('ok');
